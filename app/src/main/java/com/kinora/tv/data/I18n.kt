/** Acesso aos textos no idioma atual. */
class Strings(val lang: String) {
    private val t = I18n.table(lang)

    operator fun invoke(key: String): String = t[key] ?: key

    fun f(key: String, a: String): String = invoke(key).replace("%1", a)

    fun f2(key: String, a: String, b: String): String =
        invoke(key).replace("%1", a).replace("%2", b)

    fun genre(g: String): String {
        val k = "g_" + g.lowercase()
        return t[k] ?: g
    }

    fun epCode(season: Int, episode: Int): String =
        invoke("season_short") + season + invoke("episode_short") + episode

    fun kindLabel(kind: String): String = when (kind) {
        "movie" -> invoke("kind_movie_p")
        "series" -> invoke("kind_series_p")
        "anime" -> invoke("kind_anime_p")
        "tv" -> invoke("kind_tv_p")
        "channel" -> invoke("kind_channel_p")
        else -> kind
    }

    fun kindSingular(kind: String): String = when (kind) {
        "movie" -> invoke("kind_movie_s")
        "series" -> invoke("kind_series_s")
        "anime" -> invoke("kind_anime_s")
        "tv" -> invoke("kind_tv_s")
        else -> ""
    }
}
